function verHorario(){

  let curso =
    document.getElementById("curso").value;

  let dia =
    document.getElementById("dia").value;

  let clave = curso + "-" + dia;

  let datos = horarios[clave];

  let div =
    document.getElementById("horario");

  if(!datos){

    div.innerHTML = `
      <p>
        No hay horario disponible
      </p>
    `;

    return;
  }

  let html =
    `<div class="tabla-horario">`;

  datos.forEach(h => {

    html += `

      <div class="hora">${h[0]}</div>

      <div class="materia">
        <h3>${h[1]}</h3>
        <p>${curso}</p>
      </div>

    `;

  });

  html += `</div>`;

  div.innerHTML = html;

}

