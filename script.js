function mostrar(){

  let lista =
    JSON.parse(
      localStorage.getItem("recordatorios")
    ) || [];

  let ul =
    document.getElementById("lista");

  ul.innerHTML = "";

  let ahora = new Date();

  lista = lista.filter((r) => {

    let fechaRecordatorio =
      new Date(r.fecha + "T" + r.hora);

    return fechaRecordatorio > ahora;

  });

  localStorage.setItem(
    "recordatorios",
    JSON.stringify(lista)
  );

  lista.forEach((r, index) => {

    let li =
      document.createElement("li");

    li.className = r.tipo;

    li.innerHTML = `

      <strong>${r.mensaje}</strong><br>

      📅 ${r.fecha}
      ⏰ ${r.hora}

      <br><br>

      <button onclick="eliminar(${index})">

        ❌ Eliminar

      </button>

    `;

    ul.appendChild(li);

  });

}
mostrar();

function eliminar(index){

  let lista =
    JSON.parse(
      localStorage.getItem("recordatorios")
    ) || [];

  lista.splice(index, 1);

  localStorage.setItem(
    "recordatorios",
    JSON.stringify(lista)
  );

  mostrar();

}
